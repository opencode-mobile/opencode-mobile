import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { ICON_STROKE_WIDTH } from "./utils.mjs";

const IMAGESET_CONTENTS = `{
  "images" : [
    {
      "filename" : "icon.svg",
      "idiom" : "universal"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  },
  "properties" : {
    "preserves-vector-representation" : true,
    "template-rendering-intent" : "template"
  }
}
`;

function normalizeLucideSvgForIos(svgText) {
  return svgText
    .replaceAll('stroke="currentColor"', 'stroke="#000000"')
    .replaceAll('fill="currentColor"', 'fill="#000000"')
    .replace(/stroke-width="[^"]*"/g, `stroke-width="${ICON_STROKE_WIDTH}"`);
}

export function generateIosAssets(icons, svgByName, xcassetsDir) {
  rmSync(xcassetsDir, { recursive: true, force: true });
  mkdirSync(xcassetsDir, { recursive: true });
  writeFileSync(
    join(xcassetsDir, "Contents.json"),
    JSON.stringify(
      {
        info: { author: "xcode", version: 1 },
      },
      null,
      2,
    ) + "\n",
    "utf8",
  );

  for (const icon of icons) {
    const svgText = svgByName.get(icon.name);
    if (!svgText) throw new Error(`Missing SVG for ${icon.name}`);
    const imagesetDir = join(xcassetsDir, `${icon.iosAssetName}.imageset`);
    mkdirSync(imagesetDir, { recursive: true });
    writeFileSync(join(imagesetDir, "icon.svg"), normalizeLucideSvgForIos(svgText), "utf8");
    writeFileSync(join(imagesetDir, "Contents.json"), IMAGESET_CONTENTS, "utf8");
  }
}

export function generateIosSwiftEnum(icons, outputFile) {
  const cases = icons
    .map((icon) => {
      const caseName = toCamelCase(icon.name);
      return `    case ${caseName} = "${icon.iosAssetName}"`;
    })
    .join("\n");

  const swift = `// Generated by scripts/sync-icons.mjs — do not edit.
import SwiftUI

enum OpenCodeIcon: String, CaseIterable, Hashable {
${cases}

    var accessibilityIdentifier: String { rawValue }
}

/// Lucide catalog icon rendered as a template asset.
///
/// Size with size: or an outer .frame. Do not use .font — asset-catalog
/// templates ignore font the way SF Symbols do not, which previously left
/// glyphs optically oversized (edge-to-edge in tight chrome).
struct OpenCodeIconImage: View {
    let icon: OpenCodeIcon
    private let explicitSize: CGFloat?

    init(icon: OpenCodeIcon, size: CGFloat? = nil) {
        self.icon = icon
        self.explicitSize = size
    }

    var body: some View {
        Image(icon.rawValue)
            .renderingMode(.template)
            .resizable()
            .scaledToFit()
            .frame(width: explicitSize, height: explicitSize)
    }
}
`;

  mkdirSync(dirname(outputFile), { recursive: true });
  writeFileSync(outputFile, swift, "utf8");
}

function toCamelCase(snake) {
  const parts = snake.split("_").filter(Boolean);
  if (parts.length === 0) return snake;
  return parts
    .map((part, index) => (index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join("");
}
